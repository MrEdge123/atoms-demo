import type { CompileError } from './build';

/**
 * Virtual file system passed between the AI engineer, the builder, and the repository.
 * Keys are normalized POSIX paths such as "src/App.tsx".
 */
export type VirtualFS = Record<string, string>;

/**
 * Capability flags declared by a product plan to control which @atoms/cloud
 * runtime modules and prompts are injected into the generated app.
 */
export type CloudCapability = 'db' | 'auth' | 'billing' | 'ai';

/**
 * Canonical web UI scenario categories distilled from the UI Design Reference Manual.
 */
export type DesignScenarioId = 'A' | 'B' | 'C' | 'D' | 'E' | 'F' | 'G';

/**
 * Reusable built-in or user-authored visual style theme / prompt preset.
 */
export interface StyleThemeSpec {
  id: string;
  name: string;
  description?: string;
  scenario?: DesignScenarioId;
  colorMode: 'light' | 'dark';
  palette: {
    background: string;
    surface: string;
    textPrimary: string;
    textMuted: string;
    accent: string;
  };
  typography: {
    headingStyle: 'editorial-serif' | 'geometric-sans' | 'minimal-sans';
    bodyStyle: 'sans' | 'serif';
  };
  radiusStyle?: 'sharp' | 'soft' | 'pill';
  surfaceDepth?: 'hairline' | 'subtle-shadow' | 'stepped-dark';
  stylePrompt: string;
  isCustom?: boolean;
}

/**
 * Structured visual design system specification produced during Emma planning
 * and materialized into project DESIGN.md before code generation begins.
 */
export interface DesignSystemSpec {
  scenario: DesignScenarioId;
  scenarioName: string;
  tone: string;
  colorMode: 'light' | 'dark';
  palette: {
    background: string;
    surface: string;
    textPrimary: string;
    textMuted: string;
    accent: string;
  };
  typography: {
    headingStyle: 'editorial-serif' | 'geometric-sans' | 'minimal-sans';
    bodyStyle: 'sans' | 'serif';
    rationale: string;
  };
  radiusStyle?: 'sharp' | 'soft' | 'pill';
  surfaceDepth?: 'hairline' | 'subtle-shadow' | 'stepped-dark';
  layoutBlueprint: string;
  visualFocalPoint: string;
  motionStyle: string;
  mediaStrategy?: string;
  antiPatterns: string[];
  themeId?: string;
  themeName?: string;
  customStylePrompt?: string;
}

/**
 * Structured product specification generated by Emma and confirmed by the user
 * before code generation begins.
 */
export interface ProductPlan {
  appName: string;
  summary: string;
  targetUsers: string;
  capabilities: CloudCapability[];
  seo?: {
    title: string;
    description: string;
  };
  pages: Array<{
    name: string;
    purpose: string;
  }>;
  collections: Array<{
    name: string;
    fields: string[];
    description: string;
  }>;
  designSystem?: DesignSystemSpec;
}

/**
 * Candidate solution generated during Race Mode for side-by-side comparison.
 */
export interface RaceBranch {
  branchId: string;
  label: string;
  styleDirection: string;
  designSystem?: DesignSystemSpec;
  files: VirtualFS;
  previewHtml: string | null;
  errors: CompileError[];
}

/**
 * Lifecycle states for a project workspace in the SOP pipeline.
 */
export type ProjectStatus =
  | 'idle'
  | 'researching'
  | 'planning'
  | 'awaiting_confirmation'
  | 'building'
  | 'awaiting_branch_selection'
  | 'ready'
  | 'published'
  | 'error';

/**
 * Core project aggregate maintaining strict isolation between draft code
 * and the currently published production HTML bundle.
 */
export interface Project {
  id: string;
  slug: string;
  title: string;
  status: ProjectStatus;
  plan: ProductPlan | null;
  draftFiles: VirtualFS;
  raceBranches: RaceBranch[];
  publishedFiles: VirtualFS | null;
  publishedHtml: string | null;
  publishedVersion: number;
  capabilities: CloudCapability[];
  createdAt: string;
  updatedAt: string;
}

/**
 * End-user account scoped strictly to a single generated application (projectId).
 */
export interface AppUser {
  id: string;
  projectId: string;
  email: string;
  name: string | null;
  role: 'user' | 'admin';
  plan: 'free' | 'pro';
  createdAt: string;
}

/**
 * Generic persisted document stored in a generated application's collection.
 */
export interface AppRecord<T = Record<string, unknown>> {
  id: string;
  projectId: string;
  collection: string;
  ownerUserId: string | null;
  data: T;
  createdAt: string;
  updatedAt: string;
}
